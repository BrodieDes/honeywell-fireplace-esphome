"""Generate esphome/fireplace_codes.h from the captured frames, and verify it.

Every captured state is rebuilt from the generated tables and compared, cyclically,
with the half-bit stream the real remote sent. Any mismatch aborts without writing.

Usage:  python tools/gen_codes.py            # DEFAULT_CODE = the captured remote
        python tools/gen_codes.py --public   # DEFAULT_CODE = 0: no remote until one is learned
"""
import json
import sys
from collections import Counter
from pathlib import Path

from decode import frame, halfbits, period

ROOT = Path(__file__).resolve().parent.parent
SESSIONS = ["session-20261030-151616.jsonl", "session-20261030-152426.jsonl",
            "session-20261030-154420.jsonl"]
SYNC = "110010011011001100100110"
TAIL_BITS, ID_BITS, STATE_BITS = 25, 28, 20


def manchester_decode(hb: str) -> str:
    return "".join("1" if hb[i:i + 2] == "10" else "0" if hb[i:i + 2] == "01" else "?"
                   for i in range(0, len(hb) - 1, 2))


def manchester_encode(bits: str) -> str:
    return "".join("10" if b == "1" else "01" for b in bits)


def xor(*vals: str) -> str:
    return "".join(str(sum(int(v[i]) for v in vals) % 2) for i in range(len(vals[0])))


def parse_state(display: str) -> tuple | None:
    """'Flame 3, fan 0.' -> ('on', 3, 0); 'Off' -> ('off',). Tolerates dictation noise."""
    d = display.lower().replace("zero", "0").replace("flight", "flame")
    # Dictation heard "fan 0" as "Pantera" / "and 0" / "answer".
    for heard in ("pantera", "answer", " and 0"):
        d = d.replace(heard, " fan 0")
    if d.strip(" .") == "off":
        return ("off",)
    nums = [int(c) for c in d if c.isdigit()]
    if "flame" in d and "fan" in d and len(nums) == 2:
        return ("on", nums[0], nums[1])
    return None


def collect() -> dict:
    """Map state -> Counter of sync-aligned 170 half-bit frames."""
    frames: dict = {}
    for name in SESSIONS:
        for line in open(ROOT / "captures" / name):
            row = json.loads(line)
            state = parse_state(row["display"])
            if state is None:
                continue
            for cap in row["captures"]:
                s = halfbits(cap)
                if len(cap) < 400 or period(s) != 170:
                    continue
                f = frame(s, 170)
                k = (f + f).find(SYNC)
                if k >= 0:
                    frames.setdefault(state, Counter())[(f + f)[k:k + 170]] += 1
    return frames


def main() -> None:
    frames = collect()
    # A capture can catch the remote mid-change and carry the previous state's frame.
    # Settle unambiguous states first, then drop frames they own from the rest.
    winner = {st: next(iter(fs)) for st, fs in frames.items() if len(fs) == 1}
    for st, fs in frames.items():
        if st in winner:
            continue
        own = Counter({f: n for f, n in fs.items() if f not in winner.values()})
        winner[st] = own.most_common(1)[0][0]
        print(f"Note: {st} had {len(fs)} distinct frames; dropped {len(fs) - len(own)} "
              f"belonging to other states, kept the most common of the rest")

    data = {st: manchester_decode(f[len(SYNC):]) for st, f in winner.items()}
    base = data[("on", 0, 0)]
    head_id, tail = base[:ID_BITS], base[ID_BITS + STATE_BITS:]
    for st, bits in data.items():
        assert bits[:ID_BITS] == head_id and bits[ID_BITS + STATE_BITS:] == tail, st
    state = {st: bits[ID_BITS:ID_BITS + STATE_BITS] for st, bits in data.items()}

    flame = [state[("on", f, 0)] for f in range(7)]
    fan = [state[("on", 0, m)] for m in range(7)]
    off = state[("off",)]

    def build(st: tuple) -> str:
        """Half-bits for one frame in transmit order: tail (preamble) + SYNC + ID + state."""
        s = off if st[0] == "off" else xor(flame[st[1]], fan[st[2]], state[("on", 0, 0)])
        return manchester_encode(tail) + SYNC + manchester_encode(head_id + s)

    checked = 0
    for st, captured in winner.items():
        assert build(st) in captured + captured, f"rebuilt frame for {st} does not match capture"
        checked += frames[st][captured]
    print(f"Verified {len(winner)} states ({checked} captures); every state rebuilds exactly.")

    assert len(tail) == TAIL_BITS, len(tail)
    code = int(tail + head_id, 2)  # tail bits, then ID bits: everything but the state
    if "--public" in sys.argv:
        code = 0  # never publish a real remote's ID
    rows = lambda vals: ",\n".join(f'    "{v}"' for v in vals)
    header = f'''// Generated by tools/gen_codes.py from captures/ -- do not edit by hand.
// Honeywell RT8220A frame builder and decoder. See protocol-notes.md.
//
// One frame, in transmit order: tail (25 bits) + SYNC + transmitter ID (28 bits) + state
// (20 bits), the bits Manchester-coded ("1" = high-low). A remote's "code" is its tail and
// ID packed into one number: everything in the frame except the state.
#pragma once
#include <cstdint>
#include <cstring>
#include <map>
#include <string>
#include <tuple>
#include <vector>

namespace fireplace {{

static const int32_t HALF_BIT_US = 208;  // measured 207.9 us
static const int REPEATS = 28;           // ~1 s of back-to-back frames, like the remote
static const int TAIL_BITS = {TAIL_BITS}, ID_BITS = {ID_BITS}, STATE_BITS = {STATE_BITS};
static const char *const SYNC = "{SYNC}";  // half-bits, not Manchester

// The remote the board copies until another is learned. 0 = none: nothing is sent until
// "Learn Remote" has been used.
static const uint64_t DEFAULT_CODE = 0x{code:X}ULL;

// 20-bit state fields. state(f, m) = FLAME[f] ^ FAN[m] ^ FLAME[0].
static const char *const FLAME[7] = {{
{rows(flame)}}};
static const char *const FAN[7] = {{
{rows(fan)}}};
static const char *const OFF = "{off}";

inline uint32_t code_id(uint64_t code) {{ return code & ((1UL << ID_BITS) - 1); }}
inline uint32_t code_tail(uint64_t code) {{ return code >> ID_BITS; }}

// Manchester half-bits for the low `bits` bits of v, most significant first.
inline std::string manchester(uint64_t v, int bits) {{
  std::string hb;
  for (int i = bits - 1; i >= 0; i--)
    hb += (v >> i) & 1 ? "10" : "01";
  return hb;
}}

// Half-bits of SYNC + ID; the 40 half-bits after it carry the state.
inline std::string sync_id(uint64_t code) {{ return SYNC + manchester(code_id(code), ID_BITS); }}

// The 20-bit state field for one state. off=true ignores flame/fan.
inline std::string state_bits(bool off, int flame, int fan) {{
  if (off)
    return OFF;
  std::string bits;
  for (int i = 0; i < STATE_BITS; i++)
    bits += ((FLAME[flame][i] ^ FAN[fan][i] ^ FLAME[0][i]) & 1) ? '1' : '0';
  return bits;
}}

// Finds the state for a 20-bit field. Returns false if it isn't a known state.
inline bool lookup_state(const std::string &bits, bool &off, int &flame, int &fan) {{
  if (bits == OFF) {{
    off = true, flame = 0, fan = 0;
    return true;
  }}
  for (int f = 0; f < 7; f++)
    for (int m = 0; m < 7; m++)
      if (bits == state_bits(false, f, m)) {{
        off = false, flame = f, fan = m;
        return true;
      }}
  return false;
}}

// Timings for REPEATS frames of one state from the remote with this code.
inline std::vector<int32_t> build_frames(uint64_t code, bool off, int flame, int fan) {{
  flame = flame < 0 ? 0 : flame > 6 ? 6 : flame;
  fan = fan < 0 ? 0 : fan > 6 ? 6 : fan;
  std::string hb = manchester(code_tail(code), TAIL_BITS) + sync_id(code);
  for (char bit : state_bits(off, flame, fan))
    hb += bit == '1' ? "10" : "01";
  std::string stream;
  for (int r = 0; r < REPEATS; r++)
    stream += hb;
  std::vector<int32_t> out;
  for (size_t i = 0; i < stream.size();) {{
    size_t j = i;
    while (j < stream.size() && stream[j] == stream[i])
      j++;
    int32_t us = static_cast<int32_t>(j - i) * HALF_BIT_US;
    out.push_back(stream[i] == '1' ? us : -us);
    i = j;
  }}
  return out;
}}

// Receiver timings to half-bits. '|' marks a gap or noise; no frame spans it.
inline std::string to_halfbits(const std::vector<int32_t> &raw) {{
  std::string hb;
  for (int32_t t : raw) {{
    // The receiver reads highs ~45 us short and lows ~45 us long.
    int32_t us = t > 0 ? t : -t;
    int n = t > 0 ? (us < 290 ? 1 : us < 600 ? 2 : 0) : (us < 330 ? 1 : us < 650 ? 2 : 0);
    if (n == 0)
      hb += '|';
    else
      hb.append(n, t > 0 ? '1' : '0');
  }}
  return hb;
}}

// Manchester half-bits back to bits; false on anything that isn't "10" or "01".
inline bool unmanchester(const std::string &hb, size_t pos, int bits, std::string &out) {{
  out.clear();
  if (pos + 2 * bits > hb.size())
    return false;
  for (int i = 0; i < bits; i++) {{
    if (hb.compare(pos + 2 * i, 2, "10") == 0)
      out += '1';
    else if (hb.compare(pos + 2 * i, 2, "01") == 0)
      out += '0';
    else
      return false;
  }}
  return true;
}}

// Decodes a capture from the remote with this code. Returns false unless it holds a full
// frame with that remote's ID and a known state.
inline bool decode_frames(const std::vector<int32_t> &raw, uint64_t code, bool &off, int &flame, int &fan) {{
  std::string hb = to_halfbits(raw), want = sync_id(code), bits;
  // A capture can span two presses (FLAME then UP), so the last valid frame wins.
  bool found = false;
  for (size_t k = hb.find(want); k != std::string::npos; k = hb.find(want, k + 1))
    if (unmanchester(hb, k + want.size(), STATE_BITS, bits) && lookup_state(bits, off, flame, fan))
      found = true;
  return found;
}}

// Reads any remote's code from a capture, for "Learn remote". Needs the same complete frame
// (tail, ID and state) at least twice. A press can carry more than one distinct frame (OFF
// does), so a frame with a known state wins over the most repeated one. known_state says
// whether the state field is one of ours: if not, that remote's flame/fan codes differ from
// these tables, and state_out holds the unknown field for the log.
inline bool learn_code(const std::vector<int32_t> &raw, uint64_t &code, bool &known_state, bool &off,
                       int &flame, int &fan, std::string *state_out = nullptr) {{
  std::string hb = to_halfbits(raw), tail, id, state;
  const size_t tail_hb = 2 * TAIL_BITS, sync_len = strlen(SYNC);
  std::map<std::tuple<std::string, std::string, std::string>, int> seen;
  for (size_t k = hb.find(SYNC); k != std::string::npos; k = hb.find(SYNC, k + 1)) {{
    if (k < tail_hb || !unmanchester(hb, k - tail_hb, TAIL_BITS, tail) ||
        !unmanchester(hb, k + sync_len, ID_BITS, id) ||
        !unmanchester(hb, k + sync_len + 2 * ID_BITS, STATE_BITS, state))
      continue;
    seen[std::make_tuple(tail, id, state)]++;
  }}
  const std::tuple<std::string, std::string, std::string> *best = nullptr;
  int best_n = 0;
  bool best_known = false;
  for (const auto &kv : seen) {{
    if (kv.second < 2)
      continue;
    bool o;
    int f, m;
    bool known = lookup_state(std::get<2>(kv.first), o, f, m);
    if ((known && !best_known) || (known == best_known && kv.second > best_n))
      best = &kv.first, best_n = kv.second, best_known = known;
  }}
  if (best == nullptr)
    return false;
  code = std::stoull(std::get<0>(*best) + std::get<1>(*best), nullptr, 2);
  known_state = lookup_state(std::get<2>(*best), off, flame, fan);
  if (state_out != nullptr)
    *state_out = std::get<2>(*best);
  return true;
}}

}}  // namespace fireplace
'''
    (ROOT / "esphome" / "fireplace_codes.h").write_text(header, encoding="utf-8")
    print("Wrote esphome/fireplace_codes.h")


if __name__ == "__main__":
    sys.exit(main())
